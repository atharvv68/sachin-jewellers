// ---------- Helpers ----------

export const formatINR = (n) =>
  new Intl.NumberFormat("en-IN", {
    style: "currency",
    currency: "INR",
    maximumFractionDigits: 0,
  }).format(n);

// Price comes straight from the size row. Never compute it.
export const priceOf = (size) => size.price;

export const defaultSize = (variant) =>
  variant.sizes[Math.floor(variant.sizes.length / 2)];

export const findSize = (variant, label) =>
  variant.sizes.find((s) => s.label === label) || null;

export const priceRange = (variant) => {
  const p = variant.sizes.map((s) => s.price);
  return { from: Math.min(...p), to: Math.max(...p) };
};

export const hasColours = (product) =>
  product.variants.length > 1 && product.variants[0].color !== null;

export const defaultVariant = (product) => product.variants[0];

export const byCategory = (cat) =>
  cat && cat !== "All" ? products.filter((p) => p.category === cat) : products;

export const getProduct = (id) => products.find((p) => p.id === id);

export const getVariantBySlug = (slug) => {
  for (const p of products) {
    const v = p.variants.find((x) => x.slug === slug);
    if (v) return { product: p, variant: v };
  }
  return null;
};

export const allVariants = products.flatMap((p) =>
  p.variants.map((v) => ({
    ...v,
    productId: p.id,
    productName: p.name,
    category: p.category,
  }))
);

